/**
 * Validates road strip totals and configuration.
 * Verifies each strip has finite positive width and total corridor width remains valid.
 */
export function validateStripTotals(
  strips: Array<{ widthMeters?: unknown; kind?: string; id?: string }>
): EditValidationResult {
  if (!Array.isArray(strips) || strips.length === 0) {
    return { valid: false, error: 'Road must have at least one strip', field: 'strips' }
  }
  let total = 0
  for (let i = 0; i < strips.length; i++) {
    const s = strips[i]
    const w = s.widthMeters
    if (typeof w !== 'number' || !Number.isFinite(w) || w <= 0) {
      return {
        valid: false,
        error: `Strip "${s.id || s.kind || i}" must have a finite positive width`,
        field: 'strips'
      }
    }
    total += w
  }
  if (total <= 0 || !Number.isFinite(total)) {
    return { valid: false, error: 'Total road corridor width must be finite and positive', field: 'strips' }
  }
  if (total > 200) {
    return { valid: false, error: `Total road corridor width (${total.toFixed(1)}m) exceeds maximum limit (200m)`, field: 'strips' }
  }
  return { valid: true }
}

/**
 * Validates road lanes configuration (total lanes and forward/backward split).
 */
export function validateRoadLanes(
  lanes: unknown,
  directional?: { forwardLanes?: unknown; backwardLanes?: unknown }
): EditValidationResult {
  if (typeof lanes !== 'number' || !Number.isFinite(lanes)) {
    return { valid: false, error: 'Lanes must be a valid finite number', field: 'lanes' }
  }
  if (lanes <= 0 || !Number.isInteger(lanes)) {
    return { valid: false, error: 'Lanes must be a positive integer', field: 'lanes' }
  }
  if (lanes > 30) {
    return { valid: false, error: 'Lanes cannot exceed 30', field: 'lanes' }
  }

  if (directional) {
    const { forwardLanes, backwardLanes } = directional
    if (forwardLanes !== undefined && forwardLanes !== null) {
      if (typeof forwardLanes !== 'number' || !Number.isFinite(forwardLanes) || forwardLanes < 0 || !Number.isInteger(forwardLanes)) {
        return { valid: false, error: 'Forward lanes must be a non-negative integer', field: 'forwardLanes' }
      }
    }
    if (backwardLanes !== undefined && backwardLanes !== null) {
      if (typeof backwardLanes !== 'number' || !Number.isFinite(backwardLanes) || backwardLanes < 0 || !Number.isInteger(backwardLanes)) {
        return { valid: false, error: 'Backward lanes must be a non-negative integer', field: 'backwardLanes' }
      }
    }
    if (
      typeof forwardLanes === 'number' &&
      typeof backwardLanes === 'number' &&
      forwardLanes + backwardLanes > 0 &&
      forwardLanes + backwardLanes !== lanes
    ) {
      return {
        valid: false,
        error: `Sum of directional lanes (${forwardLanes} forward + ${backwardLanes} backward = ${forwardLanes + backwardLanes}) must match total lanes (${lanes})`,
        field: 'lanes'
      }
    }
  }

  return { valid: true }
}

/**
 * Validates speed limit value.
 */
export function validateRoadSpeedLimit(speedLimit: unknown): EditValidationResult {
  if (speedLimit === null || speedLimit === undefined) {
    return { valid: true }
  }
  if (typeof speedLimit !== 'number' || !Number.isFinite(speedLimit)) {
    return { valid: false, error: 'Speed limit must be a valid finite number', field: 'speedLimit' }
  }
  if (speedLimit <= 0) {
    return { valid: false, error: 'Speed limit must be greater than 0', field: 'speedLimit' }
  }
  if (speedLimit > 300) {
    return { valid: false, error: 'Speed limit exceeds plausible maximum (300)', field: 'speedLimit' }
  }
  return { valid: true }
}

/**
 * Validates road property combinations (e.g. direction vs one-way and directional lanes).
 */
export function validateRoadProperties(options: {
  direction?: 'forward' | 'backward' | 'both'
  lanes?: number
  forwardLanes?: number | null
  backwardLanes?: number | null
  surface?: string
  highwayClass?: string
}): EditValidationResult {
  const { direction, lanes, forwardLanes, backwardLanes, surface, highwayClass } = options
  if (lanes !== undefined && (lanes <= 0 || !Number.isFinite(lanes))) {
    return { valid: false, error: 'Road lanes must be a positive number', field: 'lanes' }
  }
  if (direction !== undefined && !['forward', 'backward', 'both'].includes(direction)) {
    return { valid: false, error: `Invalid road direction: ${direction}`, field: 'direction' }
  }
  if (surface !== undefined && typeof surface === 'string' && surface.trim().length === 0) {
    return { valid: false, error: 'Road surface cannot be empty', field: 'surface' }
  }
  if (highwayClass !== undefined && typeof highwayClass === 'string' && highwayClass.trim().length === 0) {
    return { valid: false, error: 'Highway class cannot be empty', field: 'highwayClass' }
  }
  return { valid: true }
}

/**
 * Validates coordinate pair [lon, lat] is finite and within standard geographic bounds.
 */
export function isValidCoordinate(lon: unknown, lat: unknown): boolean {
  if (typeof lon !== 'number' || typeof lat !== 'number') return false
  if (!Number.isFinite(lon) || !Number.isFinite(lat)) return false
  if (lon < -180 || lon > 180) return false
  if (lat < -90 || lat > 90) return false
  return true
}

/**
 * Recursively inspects GeoJSON geometry coordinate structures.
 */
export function validateGeometryStructure(geom: unknown): {
  valid: boolean
  error?: string
} {
  if (!geom || typeof geom !== 'object') {
    return { valid: false, error: 'Geometry is null or not an object' }
  }

  if (!('type' in geom) || typeof geom.type !== 'string') {
    return { valid: false, error: 'Geometry missing string type' }
  }

  const geomType = geom.type
  const coords = 'coordinates' in geom ? geom.coordinates : undefined

  switch (geomType) {
    case 'Point': {
      if (!Array.isArray(coords) || coords.length < 2) {
        return { valid: false, error: 'Point geometry requires at least [lon, lat] coordinates' }
      }
      const lon = coords[0]
      const lat = coords[1]
      if (!isValidCoordinate(lon, lat)) {
        return { valid: false, error: `Point coordinates out of bounds: [${lon}, ${lat}]` }
      }
      return { valid: true }
    }

    case 'MultiPoint': {
      if (!Array.isArray(coords)) {
        return { valid: false, error: 'MultiPoint geometry requires coordinates array' }
      }
      for (const pt of coords) {
        if (!Array.isArray(pt) || pt.length < 2 || !isValidCoordinate(pt[0], pt[1])) {
          return { valid: false, error: 'Invalid coordinate in MultiPoint' }
        }
      }
      return { valid: true }
    }

    case 'LineString': {
      if (!Array.isArray(coords) || coords.length < 2) {
        return { valid: false, error: 'LineString geometry requires at least 2 points' }
      }
      for (const pt of coords) {
        if (!Array.isArray(pt) || pt.length < 2 || !isValidCoordinate(pt[0], pt[1])) {
          return { valid: false, error: 'Invalid coordinate in LineString' }
        }
      }
      return { valid: true }
    }

    case 'MultiLineString': {
      if (!Array.isArray(coords)) {
        return { valid: false, error: 'MultiLineString geometry requires coordinates array' }
      }
      for (const line of coords) {
        if (!Array.isArray(line) || line.length < 2) {
          return { valid: false, error: 'Each LineString in MultiLineString requires at least 2 points' }
        }
        for (const pt of line) {
          if (!Array.isArray(pt) || pt.length < 2 || !isValidCoordinate(pt[0], pt[1])) {
            return { valid: false, error: 'Invalid coordinate in MultiLineString' }
          }
        }
      }
      return { valid: true }
    }

    case 'Polygon': {
      if (!Array.isArray(coords) || coords.length === 0) {
        return { valid: false, error: 'Polygon requires at least an outer ring' }
      }
      for (const ring of coords) {
        if (!Array.isArray(ring) || ring.length < 4) {
          return { valid: false, error: 'Polygon ring requires at least 4 coordinates (closed linear ring)' }
        }
        for (const pt of ring) {
          if (!Array.isArray(pt) || pt.length < 2 || !isValidCoordinate(pt[0], pt[1])) {
            return { valid: false, error: 'Invalid coordinate in Polygon' }
          }
        }
      }
      return { valid: true }
    }

    case 'MultiPolygon': {
      if (!Array.isArray(coords)) {
        return { valid: false, error: 'MultiPolygon requires coordinates array' }
      }
      for (const poly of coords) {
        if (!Array.isArray(poly) || poly.length === 0) {
          return { valid: false, error: 'Each polygon in MultiPolygon requires at least an outer ring' }
        }
        for (const ring of poly) {
          if (!Array.isArray(ring) || ring.length < 4) {
            return { valid: false, error: 'Polygon ring requires at least 4 coordinates (closed linear ring)' }
          }
          for (const pt of ring) {
            if (!Array.isArray(pt) || pt.length < 2 || !isValidCoordinate(pt[0], pt[1])) {
              return { valid: false, error: 'Invalid coordinate in MultiPolygon' }
            }
          }
        }
      }
      return { valid: true }
    }

    case 'GeometryCollection': {
      const geometries = 'geometries' in geom ? geom.geometries : undefined
      if (!Array.isArray(geometries)) {
        return { valid: false, error: 'GeometryCollection requires geometries array' }
      }
      for (const subGeom of geometries) {
        const subRes = validateGeometryStructure(subGeom)
        if (!subRes.valid) return subRes
      }
      return { valid: true }
    }

    default:
      return { valid: false, error: `Unsupported geometry type: ${geomType}` }
  }
}

/**
 * Inspects a raw payload (before or after normalization) to validate input type,
 * coordinates, geometry structure, and supported feature categories.
 */
export function validateImportPayload(payload: unknown): ImportValidationResult {
  const errors: string[] = []
  const warnings: string[] = []
  const stats = {
    totalFeatures: 0,
    categories: {
      road: 0,
      building: 0,
      sidewalk: 0,
      bike_lane: 0,
      junction: 0,
      unsupported: 0
    } as Record<string, number>,
    validGeometryCount: 0,
    invalidGeometryCount: 0
  }

  if (!payload || typeof payload !== 'object') {
    const err = 'Input payload is empty or not an object.'
    return {
      valid: false,
      source: 'unknown',
      errors: [err],
      warnings: [],
      stats,
      actionableAdvice: [getActionableValidationAdvice(err)]
    }
  }

  // 1. Detect input type / structure
  let detectedSource: 'osm' | 'overture' | 'custom' | 'unknown' = 'unknown'

  const rawObj = payload as Record<string, unknown>
  const hasSchemaVersionProp = 'schemaVersion' in rawObj || 'schema_version' in rawObj
  const rawSchemaVersion = hasSchemaVersionProp
    ? ('schemaVersion' in rawObj ? rawObj.schemaVersion : rawObj.schema_version)
    : undefined

  const hasFeatures = 'features' in rawObj && Array.isArray(rawObj.features)
  const hasSourceMetadata = 'sourceMetadata' in rawObj && Boolean(rawObj.sourceMetadata) && typeof rawObj.sourceMetadata === 'object'
  const isCandidateProjectEnvelope = hasSchemaVersionProp || (hasFeatures && hasSourceMetadata)

  const payloadType = 'type' in rawObj && typeof rawObj.type === 'string' ? (rawObj.type as string) : undefined
  const isOsmJson = 'elements' in rawObj && Array.isArray(rawObj.elements)
  const isOvertureGeoJson = !isCandidateProjectEnvelope && (payloadType === 'FeatureCollection' || hasFeatures) && !isOsmJson
  const hasEditorPayloadVersion =
    'editorPayloadVersion' in rawObj ||
    'editor_payload_version' in rawObj ||
    rawObj.generator === 'osm-to-godot-editor'

  if (hasEditorPayloadVersion) {
    const err = 'The selected payload is an exported scene payload (EditorGodotPayload), not a reopenable ProjectEnvelope or raw source data. To reopen and continue editing, open the saved ProjectEnvelope JSON file.'
    errors.push(err)
    return {
      valid: false,
      source: 'unknown',
      errors,
      warnings,
      stats,
      actionableAdvice: [getActionableValidationAdvice(err)]
    }
  }


  if (isCandidateProjectEnvelope) {
    if (hasSourceMetadata) {
      const meta = rawObj.sourceMetadata as Record<string, unknown>
      if (meta && typeof meta === 'object' && 'source' in meta) {
        if (meta.source === 'osm' || meta.source === 'overture' || meta.source === 'custom') {
          detectedSource = meta.source
        } else {
          detectedSource = 'custom'
        }
      } else {
        detectedSource = 'custom'
      }
    } else {
      detectedSource = 'custom'
    }

    if (!hasSchemaVersionProp || rawSchemaVersion === undefined || rawSchemaVersion === null) {
      const err = `Missing project schema version. Supported schema versions: ${SUPPORTED_PROJECT_SCHEMA_VERSIONS.join(', ')}.`
      errors.push(err)
      return {
        valid: false,
        source: detectedSource,
        errors,
        warnings,
        stats,
        actionableAdvice: [getActionableValidationAdvice(err)]
      }
    }

    if (!isSupportedSchemaVersion(rawSchemaVersion)) {
      const versionStr = typeof rawSchemaVersion === 'string' ? `"${rawSchemaVersion}"` : JSON.stringify(rawSchemaVersion)
      const err = `Unsupported project schema version: ${versionStr}. Supported schema versions: ${SUPPORTED_PROJECT_SCHEMA_VERSIONS.join(', ')}.`
      errors.push(err)
      return {
        valid: false,
        source: detectedSource,
        errors,
        warnings,
        stats,
        actionableAdvice: [getActionableValidationAdvice(err)]
      }
    }
  } else if (isOvertureGeoJson) {
    let overtureScore = 0
    let osmScore = 0
    const metaObj = rawObj.metadata
    if (metaObj && typeof metaObj === 'object') {
      const src = String((metaObj as Record<string, unknown>).source || '').toLowerCase()
      if (src.includes('overture') || 'counts' in (metaObj as Record<string, unknown>)) overtureScore += 5
      if (
        src.includes('osm') ||
        src.includes('openstreetmap') ||
        String((metaObj as Record<string, unknown>).generator || '').toLowerCase().includes('overpass')
      ) {
        osmScore += 5
      }
    }
    if ('features' in rawObj && Array.isArray(rawObj.features)) {
      for (const f of rawObj.features) {
        if (!f || typeof f !== 'object') continue
        const p = ((f as Record<string, unknown>).properties || {}) as Record<string, unknown>
        if (p.theme || p.subtype || p.class || p.subclass || p.width_rules || p.connectors) overtureScore++
        if (p.highway || p.building || p.osm_id || p.amenity) osmScore++
      }
    }
    detectedSource = overtureScore >= osmScore ? 'overture' : 'osm'
  } else if (isOsmJson) {
    detectedSource = 'osm'
  } else if (payloadType === 'Feature') {
    detectedSource = 'overture'
  }

  if (detectedSource === 'unknown') {
    const err = 'Unrecognized payload format: Expected GeoJSON FeatureCollection, OSM elements JSON, or Project Envelope.'
    errors.push(err)
    return {
      valid: false,
      source: 'unknown',
      errors,
      warnings,
      stats,
      actionableAdvice: [getActionableValidationAdvice(err)]
    }
  }

  // 2. Validate coordinates & geometries in raw Overture / GeoJSON
  if (isOvertureGeoJson && 'features' in payload && Array.isArray(payload.features)) {
    const rawFeatures = payload.features
    stats.totalFeatures = rawFeatures.length
    if (rawFeatures.length > EDITOR_SIZE_LIMITS.MAX_RECOMMENDED_FEATURES) {
      warnings.push(
        `Payload contains ${rawFeatures.length} features, which exceeds the recommended limit of ${EDITOR_SIZE_LIMITS.MAX_RECOMMENDED_FEATURES}. Performance may degrade.`
      )
    }
    for (let i = 0; i < rawFeatures.length; i++) {
      const f = rawFeatures[i]
      if (!f || typeof f !== 'object') {
        stats.invalidGeometryCount++
        continue
      }
      const geom = 'geometry' in f ? f.geometry : undefined
      if (!geom) {
        stats.invalidGeometryCount++
        warnings.push(`Feature #${i} is missing geometry.`)
        continue
      }
      const geomValidation = validateGeometryStructure(geom)
      if (!geomValidation.valid) {
        stats.invalidGeometryCount++
        warnings.push(`Feature #${i} has invalid geometry: ${geomValidation.error}`)
      } else {
        stats.validGeometryCount++
      }

      // Check category via explicit semantic kind; polygon geometry alone does not imply building
      const kind = determineOvertureSemanticKind(f as {
        geometry?: GeoJSON.Geometry
        overture_type?: string
        properties?: Record<string, unknown>
      })
      stats.categories[kind] = (stats.categories[kind] || 0) + 1
    }

    // Check for mixed-source conflation in raw GeoJSON
    let hasRawOsm = false
    let hasRawOverture = false
    for (const f of rawFeatures) {
      if (!f || typeof f !== 'object') continue
      const props = ('properties' in f && f.properties && typeof f.properties === 'object')
        ? (f.properties as Record<string, unknown>)
        : {}
      const hasOvMarker =
        'overture_type' in f ||
        'overture_type' in props ||
        ('sources' in props && Array.isArray(props.sources)) ||
        (typeof (f as Record<string, unknown>).id === 'string' &&
          ((f as Record<string, unknown>).id as string).startsWith('ov_'))
      const hasOsmMarker =
        'osm_id' in props ||
        'osm_type' in props ||
        (typeof (f as Record<string, unknown>).id === 'string' &&
          (((f as Record<string, unknown>).id as string).startsWith('way/') ||
            ((f as Record<string, unknown>).id as string).startsWith('node/') ||
            ((f as Record<string, unknown>).id as string).startsWith('relation/')))
      if (hasOvMarker) hasRawOverture = true
      if (hasOsmMarker) hasRawOsm = true
    }
    if (hasRawOsm && hasRawOverture) {
      errors.push(
        'Mixed-source GeoJSON payload detected (contains both OSM and Overture features). ' +
        'Automatic cross-source conflation is not supported; OSM and Overture must be loaded as alternative input sources.'
      )
    }
  }

  // 3. Validate coordinates & elements in raw OSM
  if (isOsmJson && 'elements' in payload && Array.isArray(payload.elements)) {
    const elements = payload.elements
    stats.totalFeatures = elements.length
    if (elements.length > EDITOR_SIZE_LIMITS.MAX_RECOMMENDED_FEATURES * 5) {
      warnings.push(
        `OSM payload contains ${elements.length} elements, which exceeds recommended size limits. Normalization and geometry recomputation may be slow.`
      )
    }

    for (const el of elements) {
      if (!el || typeof el !== 'object') continue
      const type = 'type' in el && typeof el.type === 'string' ? el.type : undefined
      const id = 'id' in el ? el.id : 'unknown'
      const tags = 'tags' in el && el.tags && typeof el.tags === 'object'
        ? (el.tags as Record<string, string>)
        : {}

      if (type === 'node') {
        const lat = 'lat' in el ? el.lat : undefined
        const lon = 'lon' in el ? el.lon : undefined
        if (!isValidCoordinate(lon, lat)) {
          stats.invalidGeometryCount++
          errors.push(`OSM Node #${id} has invalid coordinates: [${lon}, ${lat}]`)
        } else {
          stats.validGeometryCount++
        }
      } else if (type === 'way') {
        const kind = determineOsmSemanticKind(tags)
        stats.categories[kind] = (stats.categories[kind] || 0) + 1

        // Validate geometry array if present
        if ('geometry' in el && Array.isArray(el.geometry)) {
          const coords = el.geometry
          if (coords.length < 2) {
            warnings.push(`OSM Way #${id} has fewer than 2 coordinates.`)
          }
          for (const c of coords) {
            if (!c || typeof c !== 'object') continue
            const cLon = 'lon' in c ? c.lon : undefined
            const cLat = 'lat' in c ? c.lat : undefined
            if (!isValidCoordinate(cLon, cLat)) {
              stats.invalidGeometryCount++
              errors.push(`OSM Way #${id} has out-of-bounds coordinates: [${cLon}, ${cLat}]`)
              break
            }
          }
        }
      } else if (type === 'relation') {
        const isBuilding = Boolean(tags.building && tags.building !== 'no' && tags.building !== 'false')
        if (isBuilding) {
          stats.categories.building = (stats.categories.building || 0) + 1
        } else {
          stats.categories.unsupported = (stats.categories.unsupported || 0) + 1
        }
      }
    }
  }

  // 4. Validate ProjectEnvelope structure
  if (isCandidateProjectEnvelope) {
    const rawEnvelope = payload as Record<string, unknown>
    if (!hasFeatures || !Array.isArray(rawEnvelope.features)) {
      errors.push('Project envelope is missing a valid features array.')
      return { valid: false, source: detectedSource, errors, warnings, stats }
    }
    if (!hasSourceMetadata) {
      errors.push('Project envelope is missing sourceMetadata.')
      return { valid: false, source: detectedSource, errors, warnings, stats }
    }
    const projectEnv = payload as unknown as ProjectEnvelope
    stats.totalFeatures = projectEnv.features.length

    const originLon = projectEnv.projectionOrigin?.lon
    const originLat = projectEnv.projectionOrigin?.lat
    if (projectEnv.features.length > EDITOR_SIZE_LIMITS.MAX_RECOMMENDED_FEATURES) {
      warnings.push(
        `Project contains ${projectEnv.features.length} features, which exceeds the recommended limit of ${EDITOR_SIZE_LIMITS.MAX_RECOMMENDED_FEATURES}.`
      )
    }

    if (!isValidCoordinate(originLon, originLat)) {
      errors.push(`Invalid projection origin: [${originLon}, ${originLat}]`)
    } else {
      // Check projection limits (latitude limits, bounds distance, area limits)
      const projWarnings = validateProjectionLimits({
        origin: { lon: originLon, lat: originLat },
        bounds: projectEnv.selectedBounds
      })
      for (const pw of projWarnings) {
        if (pw.level === 'error') {
          errors.push(pw.message)
        } else {
          warnings.push(pw.message)
        }
      }
    }
    if (projectEnv.selectedBounds !== undefined) {
      const b = projectEnv.selectedBounds
      if (
        !Array.isArray(b) ||
        b.length !== 4 ||
        !b.every((n) => typeof n === 'number' && Number.isFinite(n)) ||
        !isValidCoordinate(b[0], b[1]) ||
        !isValidCoordinate(b[2], b[3])
      ) {
        errors.push(`Invalid selectedBounds in project envelope: ${JSON.stringify(b)}`)
      }
    }

    for (const f of projectEnv.features) {
      const gRes = validateGeometryStructure(f.sourceGeometry)
      if (!gRes.valid) {
        stats.invalidGeometryCount++
        warnings.push(`Feature ${f.id} has invalid sourceGeometry: ${gRes.error}`)
      } else {
        stats.validGeometryCount++
      }

      const cat = f.kind || f.role || 'unsupported'
      stats.categories[cat] = (stats.categories[cat] || 0) + 1
    }

    // Validate alternative input sources and prevent cross-source conflation
    const envSource = projectEnv.sourceMetadata?.source
    let hasOsmFeature = false
    let hasOvertureFeature = false

    for (const f of projectEnv.features) {
      const srcRef = f.sourceReference
      const isOverture =
        srcRef?.type === 'overture_segment' ||
        srcRef?.type === 'overture_building' ||
        Boolean(srcRef?.overtureId) ||
        Boolean(f.connectors && f.connectors.length > 0) ||
        Boolean(f.overtureSources && f.overtureSources.length > 0) ||
        Boolean(f.sourceId && (f.sourceId.startsWith('ov_') || f.sourceId.startsWith('overture_')))

      const isOsm =
        srcRef?.type === 'way' ||
        srcRef?.type === 'relation' ||
        srcRef?.type === 'node' ||
        Boolean(srcRef?.nodes && srcRef.nodes.length > 0) ||
        Boolean(f.nodes && f.nodes.length > 0) ||
        Boolean(
          f.sourceId &&
            (f.sourceId.startsWith('way/') ||
              f.sourceId.startsWith('node/') ||
              f.sourceId.startsWith('relation/') ||
              f.sourceId.startsWith('osm_'))
        )

      if (isOverture) hasOvertureFeature = true
      if (isOsm) hasOsmFeature = true
    }

    if (hasOsmFeature && hasOvertureFeature) {
      errors.push(
        'Mixed-source payload detected (contains both OSM and Overture features). ' +
        'Automatic cross-source conflation is not supported; OSM and Overture must be loaded as alternative input sources.'
      )
    } else if (envSource === 'osm' && hasOvertureFeature) {
      errors.push(
        'Project envelope is marked as OSM source, but contains Overture features. ' +
        'Automatic cross-source conflation is not supported.'
      )
    } else if (envSource === 'overture' && hasOsmFeature) {
      errors.push(
        'Project envelope is marked as Overture source, but contains OSM features. ' +
        'Automatic cross-source conflation is not supported.'
      )
    }
  }

  const isValid = errors.length === 0

  const advice: string[] = []
  for (const err of errors) {
    advice.push(getActionableValidationAdvice(err))
  }
  for (const warn of warnings) {
    advice.push(getActionableValidationAdvice(warn))
  }

  return {
    valid: isValid,
    source: detectedSource,
    errors,
    warnings,
    stats,
    actionableAdvice: advice
  }
}

export interface EditorPayloadValidationResult {
  valid: boolean
  version?: string
  errors: string[]
  warnings: string[]
  stats: {
    totalFeatures: number
    roles: Record<string, number>
    validGeometryCount: number
    invalidGeometryCount: number
  }
}

/**
 * Validates a versioned editor-to-Godot payload against schema and geometry constraints.
 */
export function validateEditorGodotPayload(payload: unknown): EditorPayloadValidationResult {
  const errors: string[] = []
  const warnings: string[] = []
  const stats = {
    totalFeatures: 0,
    roles: {} as Record<string, number>,
    validGeometryCount: 0,
    invalidGeometryCount: 0
  }

  if (!payload || typeof payload !== 'object') {
    return {
      valid: false,
      errors: ['Payload must be a non-null object.'],
      warnings,
      stats
    }
  }

  const raw = payload as Record<string, unknown>
  const version = (raw.editorPayloadVersion ?? raw.editor_payload_version ?? raw.schemaVersion) as unknown

  if (!version) {
    errors.push(
      `Missing editor payload version. Supported versions: ${SUPPORTED_EDITOR_PAYLOAD_VERSIONS.join(', ')}.`
    )
  } else if (!isSupportedEditorPayloadVersion(version)) {
    const versionStr = typeof version === 'string' ? `"${version}"` : JSON.stringify(version)
    errors.push(
      `Unsupported editor payload version: ${versionStr}. Supported versions: ${SUPPORTED_EDITOR_PAYLOAD_VERSIONS.join(', ')}.`
    )
  }

  if (raw.type !== 'FeatureCollection') {
    errors.push(`Editor-to-Godot payload type must be "FeatureCollection", got "${String(raw.type)}".`)
  }

  if (!Array.isArray(raw.features)) {
    errors.push('Editor-to-Godot payload must include a "features" array.')
    return {
      valid: false,
      version: typeof version === 'string' ? version : undefined,
      errors,
      warnings,
      stats
    }
  }

  stats.totalFeatures = raw.features.length

  for (let i = 0; i < raw.features.length; i++) {
    const f = raw.features[i] as Record<string, unknown>
    if (!f || typeof f !== 'object') {
      errors.push(`Feature at index ${i} is not an object.`)
      stats.invalidGeometryCount++
      continue
    }

    const id = f.id
    if (!id || typeof id !== 'string') {
      errors.push(`Feature at index ${i} is missing a valid string id.`)
    }

    const geom = f.geometry as GeoJSON.Geometry | undefined
    if (!geom) {
      errors.push(`Feature "${String(id ?? i)}" is missing a geometry.`)
      stats.invalidGeometryCount++
    } else {
      const geomRes = validateGeometryStructure(geom)
      if (!geomRes.valid) {
        errors.push(`Feature "${String(id ?? i)}" has invalid geometry: ${geomRes.error}`)
        stats.invalidGeometryCount++
      } else {
        stats.validGeometryCount++
      }
    }

    const props = (f.properties || {}) as Record<string, unknown>
    const role = (props.role || props.kind || 'unsupported') as string
    stats.roles[role] = (stats.roles[role] || 0) + 1
  }

  return {
    valid: errors.length === 0,
    version: typeof version === 'string' ? version : undefined,
    errors,
    warnings,
    stats
  }
}
